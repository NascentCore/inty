#!/usr/bin/env python3
"""Create companion harness epic (parent) issues and sub-issues on GitHub.

Requires ``gh`` CLI with ``issues:write`` on NascentCore/inty. Cloud Agent tokens
typically lack that scope; run locally or via maintainer PAT:

    uv run python .cursor/skills/scripts/create_companion_harness_issue_epics.py

Idempotent: skips creation when an open issue with the same title already exists.
"""

from __future__ import annotations

import json
import subprocess
import sys
from dataclasses import dataclass


REPO = "NascentCore/inty"
LABEL = "agentic_companion"


@dataclass(frozen=True)
class IssueSpec:
    title: str
    body: str
    children: tuple[IssueSpec, ...] = ()
    existing_refs: tuple[str, ...] = ()


def _run(args: list[str]) -> subprocess.CompletedProcess[str]:
    return subprocess.run(args, capture_output=True, text=True, check=False)


def _find_open_issue_by_title(title: str) -> int | None:
    r = _run(
        [
            "gh",
            "search",
            "issues",
            "--repo",
            REPO,
            f"is:issue is:open in:title {title!r}",
            "--json",
            "number,title",
            "--limit",
            "5",
        ]
    )
    if r.returncode != 0:
        return None
    for row in json.loads(r.stdout or "[]"):
        if row.get("title") == title:
            return int(row["number"])
    return None


def _create_issue(title: str, body: str) -> int:
    existing = _find_open_issue_by_title(title)
    if existing is not None:
        print(f"skip (exists): #{existing} {title}")
        return existing
    r = _run(
        [
            "gh",
            "issue",
            "create",
            "--repo",
            REPO,
            "--title",
            title,
            "--body",
            body,
            "--label",
            LABEL,
        ]
    )
    if r.returncode != 0:
        raise RuntimeError(f"gh issue create failed for {title!r}: {r.stderr.strip()}")
    url = (r.stdout or "").strip()
    number = int(url.rstrip("/").split("/")[-1])
    print(f"created: #{number} {title}")
    return number


def _render_parent_body(spec: IssueSpec, child_numbers: list[tuple[str, int]]) -> str:
    lines = [
        "> *This was generated by AI during triage.*",
        "",
        spec.body.strip(),
        "",
        "## Sub-issues",
        "",
    ]
    for label, num in child_numbers:
        lines.append(f"- [ ] #{num} — {label}")
    if spec.existing_refs:
        lines.extend(["", "## Related (pre-existing)", ""])
        for ref in spec.existing_refs:
            lines.append(f"- {ref}")
    return "\n".join(lines) + "\n"


def _render_child_body(parent_num: int, body: str) -> str:
    return "\n".join(
        [
            "> *This was generated by AI during triage.*",
            "",
            "## Parent",
            "",
            f"#{parent_num}",
            "",
            body.strip(),
            "",
        ]
    )


def _create_tree(spec: IssueSpec) -> int:
    child_links: list[tuple[str, int]] = []
    for child in spec.children:
        child_num = _create_tree(child)
        child_links.append((child.title, child_num))
    parent_body = _render_parent_body(spec, child_links)
    return _create_issue(spec.title, parent_body)


