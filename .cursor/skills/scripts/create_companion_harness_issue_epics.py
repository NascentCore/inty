def main() -> int:
    dry_run = "--dry-run" in sys.argv
    print(f"Creating companion harness epics on {REPO} (label={LABEL})")
    if dry_run:
        print("DRY RUN — no GitHub writes")
    created: list[int] = []
    for epic in EPICS:
        if dry_run:
            print(f"\n=== {epic.title} ===")
            print(epic.body[:200], "...")
            for child in epic.children:
                print(f"  - {child.title}")
            for ref in epic.existing_refs:
                print(f"  related: {ref}")
            created.append(-1)
            continue
        parent_num = _create_issue(
            epic.title,
            _render_parent_body(epic, []),
        )
        child_links: list[tuple[str, int]] = []
        for child in epic.children:
            child_body = _render_child_body(parent_num, child.body)
            child_num = _create_issue(child.title, child_body)
            child_links.append((child.title, child_num))
        updated_body = _render_parent_body(epic, child_links)
        _run(
            [
                "gh",
                "issue",
                "edit",
                str(parent_num),
                "--repo",
                REPO,
                "--body",
                updated_body,
            ]
        )
        created.append(parent_num)
        print(f"epic #{parent_num} linked {len(child_links)} sub-issues")
    print(f"done: {len(created)} epics")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except RuntimeError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        raise SystemExit(1) from exc
