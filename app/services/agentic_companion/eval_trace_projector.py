"""Project IM companion turns into chat_history for evaluation analytics (#3663).

Generated by Cursor agent for Epic #3669 eval trace readiness.
"""

from __future__ import annotations

from dataclasses import dataclass

from app.core.companion_harness.agent_channel.scope import AgentScope
from app.core.companion_harness.agentic_companion.output_queue import (
    ReadyOutputMessage,
    ready_output_delivers_user_visible_text,
)
from app.core.companion_harness.agentic_companion.types import (
    InputQueueRecord,
    OutputMessageKind,
)
from app.core.companion_harness.companion.runtime_channel import (
    ChannelKind,
    is_im_runtime_channel,
)
from app.schemas.chat_websocket import (
    ChatWsCompanionWireMessageMetaData,
    dump_chat_ws_companion_wire_meta,
)
from app.services import chat_history_service
from app.services.chat_service import generate_session_id

# TODO(#3663): extend eval trace projection to SMS when analytics needs SMS cohort rows.
_IM_ASSISTANT_PROJECTION_KINDS = frozenset(
    {
        OutputMessageKind.USER_REPLY,
        OutputMessageKind.PROACTIVE,
        OutputMessageKind.SCHEDULED,
        OutputMessageKind.MONOLOG,
    }
)


def should_project_channel(channel: ChannelKind) -> bool:
    """Return True when turns on ``channel`` must mirror into chat_history."""
    assert channel is not None
    return is_im_runtime_channel(channel)


@dataclass(frozen=True)
class EvalTraceInboundInput:
    """One IM user line before durable InputQueue enqueue."""

    scope: AgentScope
    runtime_channel: ChannelKind
    user_text: str
    queue_message_id: str


@dataclass(frozen=True)
class EvalTraceAssistantInput:
    """One assistant line after successful IM downlink delivery."""

    scope: AgentScope
    runtime_channel: ChannelKind
    ready_message: ReadyOutputMessage
    primary_input: InputQueueRecord | None


def _session_id_for_scope(scope: AgentScope) -> str:
    return generate_session_id(scope.memory_store_chat_id())


def _inbound_user_meta(
    *,
    runtime_channel: ChannelKind,
    queue_message_id: str,
) -> dict[str, object]:
    meta = ChatWsCompanionWireMessageMetaData(
        runtime_channel=runtime_channel.value,
        user_msg_uuid=queue_message_id,
    )
    return dump_chat_ws_companion_wire_meta(meta)


def _assistant_delivery_meta(
    *,
    runtime_channel: ChannelKind,
    ready_message: ReadyOutputMessage,
    primary_input: InputQueueRecord | None,
) -> dict[str, object]:
    user_msg_uuid = None
    if primary_input is not None:
        user_msg_uuid = primary_input.message_id
    elif ready_message.message_ids:
        user_msg_uuid = ready_message.message_ids[-1]
    meta = ChatWsCompanionWireMessageMetaData(
        source="chat",
        runtime_channel=runtime_channel.value,
        trace_id=ready_message.trace_id,
        langsmith_trace_id=ready_message.langsmith_trace_id,
        langsmith_run_id=ready_message.langsmith_run_id,
        user_msg_uuid=user_msg_uuid,
        assistant_msg_uuid=ready_message.message_id,
        tool_background_started=(
            True if ready_message.tool_background_started else None
        ),
    )
    return dump_chat_ws_companion_wire_meta(meta)


async def project_inbound_user(
    project_input: EvalTraceInboundInput,
) -> int | None:
    """Write one IM user row into chat_history; return inserted row id."""
    assert project_input.user_text.strip() != ""
    assert project_input.queue_message_id != ""
    if not should_project_channel(project_input.runtime_channel):
        return None
    session_id = _session_id_for_scope(project_input.scope)
    meta = _inbound_user_meta(
        runtime_channel=project_input.runtime_channel,
        queue_message_id=project_input.queue_message_id,
    )
    return await chat_history_service.add_user_message_async(
        session_id,
        project_input.user_text,
        meta_data=meta,
    )


async def project_assistant_delivery(
    project_input: EvalTraceAssistantInput,
) -> None:
    """Write one IM assistant row into chat_history after channel delivery."""
    message = project_input.ready_message
    if not should_project_channel(project_input.runtime_channel):
        return
    if message.kind not in _IM_ASSISTANT_PROJECTION_KINDS:
        return
    if not ready_output_delivers_user_visible_text(message):
        return
    text = message.text.strip()
    if not text:
        return
    session_id = _session_id_for_scope(project_input.scope)
    meta = _assistant_delivery_meta(
        runtime_channel=project_input.runtime_channel,
        ready_message=message,
        primary_input=project_input.primary_input,
    )
    await chat_history_service.add_ai_message_sync_async(
        session_id,
        message.text,
        agent_id=project_input.scope.agent_id,
        meta_data=meta,
    )
